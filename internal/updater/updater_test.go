func TestCheckAndInstall_DownloadsAndAppliesUpdate(t *testing.T) {
	fakePE := append([]byte("MZ"), make([]byte, 2046)...)
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/Mila.exe" {
			w.Header().Set("Content-Type", "application/octet-stream")
			_, _ = w.Write(fakePE)
			return
		}
		if r.URL.Path == "/SHA256SUMS.txt" {
			_, _ = w.Write([]byte(sha256Hex(fakePE) + "  Mila.exe\n"))
			return
		}
		_ = json.NewEncoder(w).Encode(GitHubRelease{
			TagName: "v0.2.0",
			HTMLURL: "https://github.com/mila-desktop/desktop/releases/tag/v0.2.0",
			Assets: []ReleaseAsset{
				{
					Name:               "Mila.exe",
					Size:               int64(len(fakePE)),
					BrowserDownloadURL: srv.URL + "/Mila.exe",
				},
				{
					Name:               DefaultChecksumAssetName,
					BrowserDownloadURL: srv.URL + "/SHA256SUMS.txt",
				},
			},
		})
	}))
	defer srv.Close()

	var mu sync.Mutex
	var events []UpdateStatus
	applied := make(chan string, 1)
	quitCalled := make(chan struct{}, 1)

	mgr := NewManager(Config{
		LatestReleaseURL: srv.URL,
		CurrentVersion:   func() string { return "v0.1.1" },
		ExecutablePath:   func() (string, error) { return "C:\\temp\\Mila.exe", nil },
		CanReplaceExe:    func(string) bool { return true },
		MinAssetBytes:    512,
		ApplyUpdate: func(stagedPath, currentExePath string, pid int, isInstaller bool) error {
			_ = os.Remove(stagedPath)
			applied <- currentExePath
			return nil
		},
	})

	initial := mgr.CheckAndInstall(
		context.Background(),
		func(st UpdateStatus) {
			mu.Lock()
			events = append(events, st)
			mu.Unlock()
		},
		func() {
			quitCalled <- struct{}{}
		},
	)

	if initial.State != "downloading" || !initial.HasUpdate {
		t.Fatalf("expected initial downloading state, got %+v", initial)
	}

	select {
	case gotExe := <-applied:
		if gotExe != "C:\\temp\\Mila.exe" {
			t.Fatalf("unexpected target exe: %s", gotExe)
		}
	case <-time.After(3 * time.Second):
		t.Fatal("timed out waiting for ApplyUpdate")
	}

	select {
	case <-quitCalled:
	case <-time.After(3 * time.Second):
		t.Fatal("timed out waiting for quitFn")
	}

	mu.Lock()
	defer mu.Unlock()
	if len(events) == 0 || events[len(events)-1].State != "installing" || events[len(events)-1].Progress != 100 {
		t.Fatalf("expected final installing event with progress 100, got %+v", events)
	}
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func TestParseChecksumManifest(t *testing.T) {
	raw := "# generated by CI\r\n" +
		strings.ToUpper(sha256Hex([]byte("portable"))) + "  Mila.exe\r\n" +
		sha256Hex([]byte("installer")) + " *Mila-installer.exe\n"

	sums, err := parseChecksumManifest(raw)
	if err != nil {
		t.Fatalf("parse failed: %v", err)
	}
	if len(sums) != 2 {
		t.Fatalf("expected 2 entries, got %+v", sums)
	}
	if sums["Mila.exe"] != sha256Hex([]byte("portable")) {
		t.Fatalf("unexpected portable hash: %s", sums["Mila.exe"])
	}
	if sums["Mila-installer.exe"] != sha256Hex([]byte("installer")) {
		t.Fatalf("unexpected installer hash: %s", sums["Mila-installer.exe"])
	}

	if _, err := parseChecksumManifest("\n\n"); err == nil {
		t.Fatal("expected error for an empty manifest")
	}
	if _, err := parseChecksumManifest("zzzz  Mila.exe\n"); err == nil {
		t.Fatal("expected error for a malformed hash")
	}
}

func TestCheckAndInstall_RejectsChecksumMismatch(t *testing.T) {
	fakePE := append([]byte("MZ"), make([]byte, 2046)...)
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/Mila.exe":
			_, _ = w.Write(fakePE)
		case "/SHA256SUMS.txt":
			_, _ = w.Write([]byte(sha256Hex([]byte("some other binary")) + "  Mila.exe\n"))
		default:
			_ = json.NewEncoder(w).Encode(GitHubRelease{
				TagName: "v0.2.0",
				Assets: []ReleaseAsset{
					{Name: "Mila.exe", Size: int64(len(fakePE)), BrowserDownloadURL: srv.URL + "/Mila.exe"},
					{Name: DefaultChecksumAssetName, BrowserDownloadURL: srv.URL + "/SHA256SUMS.txt"},
				},
			})
		}
	}))
	defer srv.Close()

	applied := make(chan struct{}, 1)
	errStates := make(chan string, 4)

	mgr := NewManager(Config{
		LatestReleaseURL: srv.URL,
		CurrentVersion:   func() string { return "v0.1.1" },
		ExecutablePath:   func() (string, error) { return "C:\\temp\\Mila.exe", nil },
		CanReplaceExe:    func(string) bool { return false },
		MinAssetBytes:    512,
		ApplyUpdate: func(string, string, int, bool) error {
			applied <- struct{}{}
			return nil
		},
	})

	mgr.CheckAndInstall(context.Background(), func(st UpdateStatus) {
		if st.State != "error" {
			return
		}
		select {
		case errStates <- st.Error:
		default:
		}
	}, nil)

	select {
	case msg := <-errStates:
		if !strings.Contains(msg, "integrity") {
			t.Fatalf("expected integrity failure, got %q", msg)
		}
	case <-time.After(3 * time.Second):
		t.Fatal("timed out waiting for the checksum failure")
	}

	select {
	case <-applied:
		t.Fatal("update must not be applied when the checksum does not match")
	case <-time.After(200 * time.Millisecond):
	}
}

func TestCheckAndInstall_RequiresChecksumManifest(t *testing.T) {
	fakePE := append([]byte("MZ"), make([]byte, 2046)...)
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/Mila.exe" {
			_, _ = w.Write(fakePE)
			return
		}
		_ = json.NewEncoder(w).Encode(GitHubRelease{
			TagName: "v0.2.0",
			Assets: []ReleaseAsset{
				{Name: "Mila.exe", Size: int64(len(fakePE)), BrowserDownloadURL: srv.URL + "/Mila.exe"},
			},
		})
	}))
	defer srv.Close()

	mgr := NewManager(Config{
		LatestReleaseURL: srv.URL,
		CurrentVersion:   func() string { return "v0.1.1" },
		ExecutablePath:   func() (string, error) { return "C:\\temp\\Mila.exe", nil },
		CanReplaceExe:    func(string) bool { return true },
		MinAssetBytes:    512,
		ApplyUpdate: func(string, string, int, bool) error {
			t.Fatal("update must not be applied without a checksum manifest")
			return nil
		},
	})

	status := mgr.CheckAndInstall(context.Background(), nil, nil)
	if status.State != "error" || !strings.Contains(status.Error, DefaultChecksumAssetName) {
		t.Fatalf("expected a missing-manifest error, got %+v", status)
	}
}
